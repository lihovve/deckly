package app.deckly.domain.model

/**
 * Единицы карточки: ширина листа 1000, `x` вправо, `y` вниз. Высота по пропорции листа макета 928 × 963. Штрихи и
 * фигуры хранятся в этих единицах и не зависят от размера листа на экране. Единица макета `design/` (1 dp на
 * планшете) равна [PER_DESIGN_UNIT] единицы карточки: размеры из демо макета (поле 32, ручка 48, остриё 24) переводятся
 * умножением на неё.
 */
object CardUnits {
    const val WIDTH = 1000f
    const val PER_DESIGN_UNIT = 1000f / 928f
    val HEIGHT = 1000f * 963f / 928f
}
